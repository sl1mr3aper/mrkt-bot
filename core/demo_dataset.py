"""Realistic demo dataset for the MRKT bot — sourced from the public
``gifts.supply`` catalog API.

We cache a snapshot of all 138 real Telegram Gift collections (their slugs,
display names, supply, floor price, real preview models, real preview
backdrops, real preview symbols) in :mod:`core._real_collections_data`. That
file is regenerated by ``scripts/refresh_collections.py`` so it always reflects
the live catalogue without requiring API credentials at runtime.

The bot uses this data when ``MRKT_API_ID`` / ``MRKT_API_HASH`` are missing
(the official ``api.tgmrkt.io`` endpoints all require a JWT obtained through
Pyrogram). The names / floors here are real; only the per-listing prices,
rarity bands and trade history are synthesised so that the analytics screens
have meaningful numbers in DRY-RUN mode.

The generators are deterministic (seeded) so the bot UI is reproducible
between restarts.
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from typing import Any

from core._real_collections_data import (
    BACKDROPS as _PREVIEW_BACKDROPS,
)
from core._real_collections_data import (
    COLLECTIONS as _RAW_COLLECTIONS,
)
from core._real_collections_data import (
    SYMBOLS as _PREVIEW_SYMBOLS,
)

# ─── public reference data ─────────────────────────────────────────


# Aliased so existing imports (`from core.demo_dataset import BACKDROPS`) keep
# working. Lists are sorted alphabetically (already sorted in the raw module).
BACKDROPS: list[str] = list(_PREVIEW_BACKDROPS)
SYMBOLS: list[str] = list(_PREVIEW_SYMBOLS)


# Public ``COLLECTIONS`` list mirrors the legacy schema used elsewhere in the
# bot (``name`` is the slug, ``title`` is the display name, ``floor`` is the
# real on-chain floor price, ``volume_24h`` is approximated from supply &
# listed_count because the public API does not expose 24h notional volume
# without auth).
COLLECTIONS: list[dict[str, Any]] = []
_MODELS_INDEX: dict[str, list[str]] = {}
_THEME_INDEX: dict[str, str] = {}


for _row in _RAW_COLLECTIONS:
    slug = _row["slug"]
    listed = float(_row.get("listed_count") or 0)
    floor = float(_row.get("floor") or 0.0) or 0.5
    # Estimate 24h notional volume: assume ~5% of listed inventory turns over
    # daily at the floor — this is a *display-only* number for the mock.
    volume_24h = round(listed * 0.05 * floor, 2)
    COLLECTIONS.append(
        {
            "name": slug,
            "title": _row["name"],
            "floor": floor,
            "volume_24h": volume_24h,
            "supply": _row.get("supply", 0),
            "models_count": _row.get("models_count", 0),
            "backdrops_count": _row.get("backdrops_count", 0),
            "symbols_count": _row.get("symbols_count", 0),
            "listed_count": _row.get("listed_count", 0),
        }
    )
    # Real preview models from gifts.supply (typically 5 names per
    # collection). A few unreleased / auction collections expose 0 preview
    # models — for those we fall back to a small set of generic style words
    # so analytics still work end-to-end. Variants here are deterministic
    # (seeded by slug) so the bot UI is reproducible between restarts.
    _preview = list(_row.get("preview_models") or [])
    if len(_preview) < 3:
        _rng = random.Random(slug)
        _palette = _rng.sample(
            [
                "Bronze",
                "Silver",
                "Gold",
                "Platinum",
                "Mythic",
                "Aurora",
                "Eclipse",
                "Frost",
                "Flame",
                "Storm",
                "Shadow",
                "Aether",
                "Crimson",
                "Cobalt",
                "Emerald",
                "Amber",
                "Onyx",
                "Vintage",
                "Modern",
                "Cyber",
            ],
            k=5,
        )
        _suffix = _rng.choice(["Edition", "Variant", "Form", "Cut", "Finish"])
        _preview = list(dict.fromkeys([*_preview, *(f"{p} {_suffix}" for p in _palette)]))[:5]
    _MODELS_INDEX[slug] = _preview
    if _row.get("theme"):
        _THEME_INDEX[slug] = _row["theme"]


# ─── helpers ───────────────────────────────────────────────────────


@dataclass
class DemoTrade:
    gift_id: str
    gift_name: str
    collection: str
    buy_price: float
    sell_price: float
    gross_profit: float
    net_profit: float
    profit_pct: float
    sold_at: datetime


def _models_for(collection: str) -> list[str]:
    """Return the real preview models recorded for ``collection``.

    Falls back to a single ``Standard`` entry when the collection has no
    cached preview (should not happen in practice — the snapshot always has
    at least 1 model per collection).
    """
    return _MODELS_INDEX.get(collection) or ["Standard"]


def _rarity_band(promille: float) -> str:
    if promille < 5:
        return "Legendary"
    if promille < 20:
        return "Epic"
    if promille < 80:
        return "Rare"
    if promille < 200:
        return "Uncommon"
    return "Common"


def make_collections() -> list[dict[str, Any]]:
    """Return collections shaped for the bot's market layer."""
    rng_master = random.Random(0xC0FFEE)
    return [
        {
            "name": c["name"],
            "title": c["title"],
            "floor_price": c["floor"],
            "volume": c["volume_24h"],
            "is_new": False,
            "previous_floor": round(
                c["floor"] * random.Random(c["name"]).uniform(0.85, 1.10), 4
            ),
            "supply": c.get("supply", 0),
            "models_count": c.get("models_count", 0),
            "backdrops_count": c.get("backdrops_count", 0),
            "symbols_count": c.get("symbols_count", 0),
            "listed_count": c.get("listed_count", 0),
            # A pseudo-random "popularity" tag so analytics has some variance
            # between identical floor-priced collections.
            "popularity": round(rng_master.random(), 3),
        }
        for c in COLLECTIONS
    ]


def make_models_index() -> dict[str, list[str]]:
    return {c["name"]: list(_models_for(c["name"])) for c in COLLECTIONS}


def make_listings(*, per_collection: int = 12, seed: int = 1337) -> list[dict[str, Any]]:
    """Return listings spread across all 138 collections.

    The number of listings per collection is capped at ``per_collection`` to
    keep memory low; the prices are derived from the real floor with a
    rarity-driven multiplier.
    """
    rng = random.Random(seed)
    out: list[dict[str, Any]] = []
    gid = 1
    for coll in COLLECTIONS:
        floor = float(coll["floor"])
        models = _models_for(coll["name"])
        for _ in range(per_collection):
            model = rng.choice(models)
            backdrop = rng.choice(BACKDROPS)
            symbol = rng.choice(SYMBOLS)
            number = rng.randint(1, max(2, int(coll.get("supply") or 9999)))
            model_promille = rng.choices(
                [3, 8, 25, 60, 120, 180, 350],
                weights=[1, 2, 4, 6, 8, 6, 4],
            )[0]
            backdrop_promille = rng.choices(
                [5, 25, 80, 150, 300],
                weights=[1, 3, 6, 6, 4],
            )[0]
            symbol_promille = rng.choices(
                [2, 8, 30, 100, 300],
                weights=[1, 2, 5, 6, 6],
            )[0]
            rarity_score = _composite_rarity_promille(
                model_promille, backdrop_promille, symbol_promille
            )
            multiplier = _price_multiplier_for_rarity(rarity_score)
            price = round(floor * rng.uniform(0.95, multiplier), 4)
            out.append({
                "id": f"g{gid}",
                "name": f"{model} #{number}",
                "title": f"{model} #{number}",
                "number": number,
                "collection": coll["name"],
                "collection_title": coll["title"],
                "model": model,
                "backdrop": backdrop,
                "symbol": symbol,
                "modelRarity": round(model_promille / 10.0, 2),
                "backdropRarity": round(backdrop_promille / 10.0, 2),
                "symbolRarity": round(symbol_promille / 10.0, 2),
                "rarity_band": _rarity_band(rarity_score),
                "is_on_sale": True,
                "is_mine": False,
                "minted": True,
                "mintable": rng.random() < 0.15,
                "price": price,
                "floor_price": floor,
            })
            gid += 1
    return out


def _composite_rarity_promille(model: float, backdrop: float, symbol: float) -> float:
    """Weighted composite (model 0.55 / backdrop 0.30 / symbol 0.15)."""
    return 0.55 * model + 0.30 * backdrop + 0.15 * symbol


def _price_multiplier_for_rarity(promille: float) -> float:
    """A rough price ladder mirroring the spec."""
    if promille < 5:
        return 9.0
    if promille < 20:
        return 5.0
    if promille < 80:
        return 3.0
    if promille < 200:
        return 1.7
    return 1.2


def make_trades(user_id: int, *, count: int = 80, seed: int = 4242) -> list[DemoTrade]:
    """Generate a fake trade history so analytics are not empty in DRY-RUN."""
    rng = random.Random(seed)
    listings = make_listings(seed=seed)
    out: list[DemoTrade] = []
    now = datetime.now(UTC)
    for _ in range(count):
        g = rng.choice(listings)
        buy = round(g["price"] * rng.uniform(0.85, 1.0), 4)
        sell = round(buy * rng.uniform(0.7, 1.6), 4)
        commission = round(sell * 0.05, 4)
        gross = round(sell - buy, 4)
        net = round(gross - commission, 4)
        pct = round((net / buy) * 100.0 if buy > 0 else 0.0, 2)
        sold_at = now - timedelta(
            hours=rng.randint(1, 24 * 30),
            minutes=rng.randint(0, 59),
        )
        out.append(
            DemoTrade(
                gift_id=g["id"],
                gift_name=g["title"],
                collection=g["collection"],
                buy_price=buy,
                sell_price=sell,
                gross_profit=gross,
                net_profit=net,
                profit_pct=pct,
                sold_at=sold_at,
            )
        )
    return out
